const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const engine=fs.readFileSync(path.join(root,'engine.js'),'utf8');
const entry=fs.readFileSync(path.join(root,'index.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
assert.doesNotThrow(()=>new vm.Script(engine));
assert.doesNotThrow(()=>new vm.Script(entry.replaceAll('export async function','async function'),{filename:'index.js'})); // Parse ES module after stripping export keywords
assert.equal(manifest.minimum_client_version,'1.17.0');
assert.equal(manifest.version,'2.4.3');
for(const [name,script] of [['engine.js',engine],['index.js',entry]]){
  assert(!/\b(?:fetch|XMLHttpRequest|WebSocket|sendBeacon|EventSource)\s*\(/.test(script), name+': unexpected network primitive');
  assert(!/\beval\s*\(/.test(script),name+': eval is prohibited');
  assert(!/new\s+Function\s*\(/.test(script),name+': dynamic JS execution is prohibited');
}
assert(!/\@import\b|url\s*\(/i.test(css),'Stylesheet must not load off-site assets');
const env={window:{__MAWS_UNIVERSAL_TEST_ONLY__:true},console,URL};
vm.runInNewContext(engine,env,{filename:'engine.js'});
const A=env.window.__MAWS_UNIVERSAL_API__;
const kind=value=>A.avatarSourceKind(value,URL);
assert.equal(kind('data:image/png;base64,aGVsbG8='),'inline');
assert.equal(kind('data:image/svg+xml;base64,PHN2Zz4='),null);
assert.equal(kind('javascript:alert(1)'),null);
assert.equal(kind('file:///etc/passwd'),null);
assert.equal(kind('https://evil.example.test/pixel.png'),'remote');
assert.equal(kind('http://localhost:8080/photo.png'),'remote');
assert.equal(kind('https://user:password@evil.example.test/track.png'),null);
assert.equal(kind('https://evil.example.test/'+('a'.repeat(2000))),null);
assert.match(engine,/approvedAvatarUrls\.has\(currentScope\(ctx\(\)\)\+'\\n'\+src\)/);
assert.match(engine,/referrerpolicy="no-referrer"/);
assert.match(engine,/data-avatar-action="allow"/);
assert(!engine.includes("preview:String(raw??'').slice(0,900)"),'Never keep raw service response in diagnostics');
const secret='sk-ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const redacted=A.redactSecrets('Bearer sensitive-test '+secret+' https://api.example.test/?api_key=TOPSECRET123');
assert(!redacted.includes('sensitive-test'));
assert(!redacted.includes(secret));
assert(!redacted.includes('TOPSECRET123'));
const malicious=JSON.parse('{"__proto__":{"admin":true},"constructor":{"shouldNot":true},"P_GOOD":{"title":"ok"}}');
const cleaned=A.safeQuestRecords(malicious);
assert(!Object.hasOwn(cleaned,'__proto__'));
assert(!Object.hasOwn(cleaned,'constructor'));
assert(Object.hasOwn(cleaned,'P_GOOD'));
const defs=A.questDefs({detachedDefs:malicious,questOverrides:malicious,packs:{p:{id:'p',quests:[{id:'__proto__',title:'unsafe'},{id:'P_REAL',title:'safe'}]}},generated:{}});
assert(Object.hasOwn(defs,'P_GOOD'));
assert(Object.hasOwn(defs,'P_REAL'));
assert(!Object.hasOwn(defs,'__proto__'));
assert.equal(({}).admin,undefined,'No prototype pollution allowed');
const unsafeProfile=JSON.parse('{"format":"maws-player-profile","format_version":1,"variant":"universal-roleplay","engine":43,"state":{},"snapshot":{"quests":{"__proto__":{"evil":true}},"people":[],"npcs":[],"scene":{"place":"X"},"world":{"investigation":[]}}}');
assert.throws(()=>A.validateProfile(unsafeProfile),/идентификатор/);
const safe=A.normalize({version:43,enabled:true,theme:{panel:'#abcabc'},promptOverrides:{'scene.core':'unchanged personal prompt'},ledger:[{kind:'manual'}]});
assert.equal(safe.enabled,true);
assert.equal(safe.theme.panel,'#abcabc');
assert.equal(safe.promptOverrides['scene.core'],'unchanged personal prompt');
assert.equal(safe.ledger.length,1);
console.log('PASS: no direct exfil channels, safe avatar consent and URL types, secret redaction, prototype-safe JSON import, existing chat settings');
