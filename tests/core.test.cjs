const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const base = path.resolve(__dirname, '..');
const engine = fs.readFileSync(path.join(base, 'engine.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(base, 'manifest.json'), 'utf8'));
assert.equal(manifest.js, 'index.js');
assert.equal(manifest.css, 'style.css');
assert.equal(manifest.requires.length, 0);
assert.match(engine, /const VERSION=43, KEY='maws_engine_universal_v1'/);
assert.match(engine, /function mawsDecorateOnce/);
assert.match(engine, /const eligible=\[\]/);
assert.match(engine, /viewCache.views.size>=16/);
assert.match(engine, /mawsOnScroll/);
assert.equal((engine.match(/linear-gradient\(/g)||[]).length,0,'UI should use solid fills');
const env = { window:{__MAWS_UNIVERSAL_TEST_ONLY__:true}, console };
vm.runInNewContext(engine, env, {filename:'engine.js'});
const A = env.window.__MAWS_UNIVERSAL_API__;
assert.ok(A, 'test APIs must be exported');
assert.equal(A.defaultState().version,43);
assert.equal(A.defaultState().sceneAuto,true);
assert.equal(A.rpElapsed('спустя два часа'),120);
assert.equal(A.rpElapsed('через полчаса'),30);
assert.equal(A.rpDateHint('Наутро','2026-11-16',0).date,'2026-11-17');
assert.equal(A.rpDateHint('2026-11-20 в 11:30','2026-11-16',0).date,'2026-11-20');
assert.equal(A.normalizeSpeakerMarker('[CLARK]'),'CLARK');
assert.ok(A.validSpeakerMarker('CLARK'));
assert.ok(!A.validSpeakerMarker('MAWS_TEST'));
assert.equal(A.promptValue({promptOverrides:{'scene.core':'мой текст'}},'scene.core'),'мой текст');
assert.ok(A.promptValue({promptOverrides:{}},'scene.core').includes('{{user}}'));
assert.equal(A.parsedTags('⟦MAWS_MEET:CLARK⟧').length,1);
const chat=[
 {is_user:true,is_system:false,name:'Ness',mes:'Привет!',extra:{},swipe_id:0},
 {is_user:false,is_system:false,name:'Clark',mes:'Кларк улыбнулся. ⟦MAWS_SCENE:Вечер|Кухня|Они разговаривают|Кларк⟧',extra:{},swipe_id:0},
];
const state = A.defaultState();
const scene = A.project(chat,state,1);
assert.ok(scene);
assert.equal(scene.scene.place,'Кухня');
const instr = A.currentFocusPrompt(scene,chat);
assert.ok(instr.includes('ВЕДЕНИЕ СЦЕНЫ'));
assert.ok(instr.includes('Кухня'));
assert.ok(!instr.includes('MAWS Universal — универсальный ролевой движок — Light (1).json'));
const baseState = A.defaultState();
baseState.promptOverrides={'scene.pacing':'Плавный ритм без спешки.'};
const prompt = A.currentFocusPrompt({...scene,promptOverrides:baseState.promptOverrides},chat);
assert.ok(prompt.includes('Плавный ритм без спешки.'));
assert.notEqual(A.hash('one'),A.hash('two'));
console.log('PASS: manifest, structural performance checks, pure engine, date/calendar, prompts, chat scene');
